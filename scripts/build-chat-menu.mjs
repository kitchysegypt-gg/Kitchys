// Regenerates supabase/functions/kitchy-chat/menu.ts from data/menu.ts and lib/loyalty.ts.
// Run after changing the menu or loyalty rules: node --experimental-strip-types scripts/build-chat-menu.mjs
import { writeFileSync } from 'node:fs';

const { CHEFS, DISHES } = await import('../data/menu.ts');
const { RANKS, REWARDS, EGP_PER_POINT } = await import('../lib/loyalty.ts');

const lines = [];
lines.push("# Kitchy's menu (prices in EGP)");
for (const chef of CHEFS) {
  lines.push(`\n## ${chef.name.en} (${chef.name.ar}) - ${chef.specialty.en}, ${chef.area.en}. Rating ${chef.rating}. ${chef.bio.en}`);
  for (const d of DISHES.filter((x) => x.chefId === chef.id)) {
    const tags = [d.vegetarian && 'vegetarian', d.spicy && 'spicy'].filter(Boolean).join(', ');
    lines.push(
      `- ${d.name.en} / ${d.name.ar} / ${d.name.fr} [${d.category}] EGP ${d.price}, ${d.prepMinutes} min, serves ${d.serves}${tags ? `, ${tags}` : ''}. ` +
        `${d.description.en} Ingredients: ${d.ingredients.en}. Allergens: ${d.allergens.length ? d.allergens.join(', ') : 'none of the common allergens'}.`
    );
  }
}
lines.push('\n# Delivery');
lines.push("- Delivery costs EGP 30. A customer's first 3 orders have free delivery.");
lines.push('\n# Points and ranks');
lines.push(`- Customers earn 1 point per EGP ${EGP_PER_POINT} spent (after discounts, before delivery), times their rank multiplier.`);
lines.push(`- Ranks by number of orders: ${RANKS.map((r) => `${r.id} ${r.minOrders}+ orders x${r.multiplier}`).join('; ')}.`);
lines.push(
  `- Rewards (redeem in the Rewards tab, then pick the voucher in the cart): ${REWARDS.map(
    (r) =>
      `${r.id}: ${r.kind === 'free_delivery' ? 'free delivery' : r.kind === 'fixed' ? `EGP ${r.value} off` : `${r.value}% off up to EGP ${r.maxDiscount}`} for ${r.cost} points` +
      (r.minRank ? ` (needs ${RANKS[r.minRank].id} rank)` : '')
  ).join('; ')}.`
);

writeFileSync(
  new URL('../supabase/functions/kitchy-chat/menu.ts', import.meta.url),
  `// Generated by scripts/build-chat-menu.mjs - do not edit by hand.\nexport const MENU = ${JSON.stringify(lines.join('\n'))};\n`
);
console.log('wrote menu.ts,', lines.join('\n').length, 'chars');
