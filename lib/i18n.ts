export const translations: Record<Language, Record<TranslationKey, string>> = { en, ar, fr };

export function translate(language: Language, key: TranslationKey, params?: Record<string, string | number>): string {
  let text = translations[language][key] ?? en[key];
  if (params) {
    for (const [name, value] of Object.entries(params)) {
      text = text.replace(`{${name}}`, String(value));
    }
  }
  return text;
}
